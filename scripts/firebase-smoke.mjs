/**
 * End-to-end test of the app in Firebase mode, against the local emulators.
 *
 * Why this exists: the unit tests prove the rules and the stores in isolation,
 * but nothing had ever driven the real app through signup → onboarding → write
 * → reload → second account. That is precisely the path that breaks when a
 * config value is wrong, and it is the path a student walks first.
 *
 * Runs inside `firebase emulators:exec`, which starts Firestore + Auth, runs
 * this file, then tears them down. No Google account, no real project, no data
 * leaves the machine.
 *
 *   npm run test:firebase
 */
import { chromium } from 'playwright';
import admin from 'firebase-admin';
import { spawn, execFileSync } from 'node:child_process';
import fs from 'node:fs';
import net from 'node:net';
import path from 'node:path';

const ROOT = process.cwd();
const PORT = 5199;
const BASE = `http://127.0.0.1:${PORT}`;
const PROJECT = 'demo-ujyalo';

const results = [];
function check(name, passed, detail = '') {
  results.push({ name, passed, detail });
  console.log(`${passed ? '✓' : '✗'} ${name}${passed || !detail ? '' : ` — ${detail}`}`);
}

function fail(message) {
  console.error(`\n✗ ${message}`);
  process.exit(1);
}

// ── Preconditions ──────────────────────────────────────────────────────────
if (!process.env.FIRESTORE_EMULATOR_HOST) {
  fail('FIRESTORE_EMULATOR_HOST is not set. Run this through `npm run test:firebase`.');
}

// ── 1. Seed the library into the emulator ──────────────────────────────────
console.log('Seeding the emulator…');
try {
  execFileSync('node', ['scripts/seed-firestore.mjs', '--project', PROJECT], {
    stdio: 'inherit',
    env: { ...process.env },
  });
} catch {
  fail('seeding failed — the app would show an empty library');
}

// ── 2. Point the dev server at the emulators ───────────────────────────────
// Dummy values: the emulator ignores the API key and sender. Written to
// .env.emulator (git-ignored) so `.env.local` with real values is untouched.
fs.writeFileSync(
  path.join(ROOT, '.env.emulator'),
  [
    '# Generated by scripts/firebase-smoke.mjs — dummy values for the emulators.',
    'VITE_FIREBASE_API_KEY=demo-api-key',
    `VITE_FIREBASE_AUTH_DOMAIN=${PROJECT}.firebaseapp.com`,
    `VITE_FIREBASE_PROJECT_ID=${PROJECT}`,
    'VITE_FIREBASE_STORAGE_BUCKET=demo-ujyalo.appspot.com',
    'VITE_FIREBASE_MESSAGING_SENDER_ID=000000000000',
    'VITE_FIREBASE_APP_ID=1:000000000000:web:demo',
    'VITE_FIREBASE_EMULATOR=true',
    'VITE_SITE_URL=http://localhost:5199',
    '',
  ].join('\n'),
);

const server = spawn(
  'npx',
  ['vite', '--mode', 'emulator', '--port', String(PORT), '--strictPort', '--host', '127.0.0.1'],
  // Detached so the whole process group can be killed: npx spawns vite as a
  // grandchild, and killing only npx leaves vite holding the port — which made
  // the run hang until an outside timeout killed it.
  { cwd: ROOT, stdio: ['ignore', 'pipe', 'pipe'], detached: true },
);
let serverLog = '';
server.stdout.on('data', (chunk) => (serverLog += chunk));
server.stderr.on('data', (chunk) => (serverLog += chunk));

async function waitForPort(port, timeoutMs = 60000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    const open = await new Promise((resolve) => {
      const socket = net.connect(port, '127.0.0.1');
      socket.on('connect', () => (socket.end(), resolve(true)));
      socket.on('error', () => resolve(false));
      socket.setTimeout(1000, () => (socket.destroy(), resolve(false)));
    });
    if (open) return true;
    await new Promise((r) => setTimeout(r, 500));
  }
  return false;
}

function cleanup() {
  try {
    process.kill(-server.pid, 'SIGKILL');
  } catch {
    // Already gone.
  }
  fs.rmSync(path.join(ROOT, '.env.emulator'), { force: true });
}

const started = Date.now();
const elapsed = () => `${((Date.now() - started) / 1000).toFixed(1)}s`;

if (!(await waitForPort(PORT))) {
  console.error(serverLog.slice(-2000));
  cleanup();
  fail('the dev server never started');
}

// ── 3. Drive the real app ──────────────────────────────────────────────────
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1360, height: 900 } });
const page = await context.newPage();
const pageErrors = [];
page.on('pageerror', (error) => pageErrors.push(error.message));

async function signUp(email, name) {
  await page.goto(`${BASE}/signup`, { waitUntil: 'domcontentloaded' });
  await page.getByLabel('Your name').fill(name);
  await page.getByLabel('Email address').fill(email);
  await page.getByLabel('Password', { exact: true }).fill('StudyHard123');
  await page.getByLabel('Confirm password').fill('StudyHard123');
  await page.getByRole('checkbox').check();
  await page.getByRole('button', { name: /create free account|create account/i }).click();
}

async function completeOnboarding() {
  await page.waitForURL('**/onboarding', { timeout: 30000 });
  await page.waitForSelector('text=Your learning profile');
  await page.getByLabel('Your name').fill('Firebase Tester');
  await page.getByRole('button', { name: 'Continue' }).click();
  await page.getByRole('button', { name: 'Grade 10', exact: true }).click();
  await page.getByRole('button', { name: 'Continue' }).click();
  await page.getByRole('button', { name: /Nepal National Curriculum/ }).click();
  await page.getByRole('button', { name: 'Continue' }).click();
  await page.getByRole('button', { name: /^English/ }).first().click();
  await page.getByRole('button', { name: 'Continue' }).click();
  await page.getByRole('button', { name: 'Mathematics', exact: true }).click();
  await page.getByRole('button', { name: 'Continue' }).click();
  await page.getByRole('button', { name: /Prepare for exams/i }).click();
  await page.getByRole('button', { name: 'Continue' }).click();
  await page.getByRole('button', { name: /Step-by-step detailed/i }).click();
  await page.getByRole('button', { name: /Finish setup/i }).click();
  await page.waitForURL('**/app', { timeout: 30000 });
}

const stamp = Date.now();
const alice = `alice.${stamp}@example.test`;
const bob = `bob.${stamp}@example.test`;

try {
  // ── Signup ───────────────────────────────────────────────────────────────
  await signUp(alice, 'Alice Emulator');
  await completeOnboarding();
  check('signup and onboarding work against Firebase', page.url().endsWith('/app'));

  // Let the profile document arrive from Firestore and the shell render.
  await page.waitForTimeout(2500);
  const shell = await page.locator('body').innerText();
  check(
    'the app reports cloud mode, not local demo mode',
    /Private to your account/i.test(shell) && !/Local demo mode/i.test(shell),
    shell.replace(/\s+/g, ' ').slice(0, 200),
  );

  // ── The seeded library is visible through Firestore ──────────────────────
  await page.goto(`${BASE}/courses`, { waitUntil: 'domcontentloaded' });
  let courses = '';
  for (let attempt = 0; attempt < 10; attempt += 1) {
    await page.waitForTimeout(800);
    courses = await page.locator('body').innerText();
    if (/learning paths|course/i.test(courses)) break;
  }
  check(
    'the seeded library renders from Firestore',
    /learning paths|course/i.test(courses),
    courses.replace(/\s+/g, ' ').slice(0, 160),
  );
  check(
    'a seeded course detail page loads from Firestore',
    (await page.goto(`${BASE}/courses/see-mathematics-core`, { waitUntil: 'domcontentloaded' }))?.status() === 200,
  );

  // ── Write, then prove it came from the server ────────────────────────────
  await page.goto(`${BASE}/app/notes`, { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(2000);
  await page.getByRole('button', { name: /new note/i }).first().click();
  await page.getByLabel('Title', { exact: true }).fill('Cloud persistence check');
  await page.getByLabel('Subject', { exact: true }).selectOption({ label: 'Science' });
  await page.getByLabel('Content', { exact: true }).fill('Written in one session, read back in another.');
  await page.getByRole('button', { name: /save note/i }).click();
  await page.waitForTimeout(2000);

  // A reload clears all in-memory state; anything still on screen is from
  // Firestore, which is the whole point of the exercise.
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(2500);
  check(
    'the note survives a reload (it is in Firestore, not memory)',
    (await page.locator('body').innerText()).includes('Cloud persistence check'),
  );

  // ── A second account must not see the first account's data ───────────────
  const aliceContext = context;
  const bobContext = await browser.newContext({ viewport: { width: 1360, height: 900 } });
  const bobPage = await bobContext.newPage();
  await bobPage.goto(`${BASE}/signup`, { waitUntil: 'domcontentloaded' });
  await bobPage.getByLabel('Your name').fill('Bob Emulator');
  await bobPage.getByLabel('Email address').fill(bob);
  await bobPage.getByLabel('Password', { exact: true }).fill('StudyHard123');
  await bobPage.getByLabel('Confirm password').fill('StudyHard123');
  await bobPage.getByRole('checkbox').check();
  await bobPage.getByRole('button', { name: /create free account|create account/i }).click();
  await bobPage.waitForURL('**/onboarding', { timeout: 30000 });
  await bobPage.goto(`${BASE}/app/notes`, { waitUntil: 'domcontentloaded' });
  await bobPage.waitForTimeout(2500);
  check(
    "a second account cannot see the first account's note",
    !(await bobPage.locator('body').innerText()).includes('Cloud persistence check'),
  );

  // ── Sign out, sign back in, data still there ─────────────────────────────
  const menu = page.locator('[aria-label="Account menu"]').first();
  await menu.click();
  await page.getByRole('menuitem', { name: /log out/i }).first().click();
  await page.waitForTimeout(2000);
  check('signing out returns to a signed-out state', !page.url().includes('/app'));

  await page.goto(`${BASE}/login`, { waitUntil: 'domcontentloaded' });
  await page.getByLabel(/email/i).first().fill(alice);
  await page.getByLabel(/^password$/i).first().fill('StudyHard123');
  await page.getByRole('button', { name: /^log in$|sign in/i }).first().click();
  await page.waitForTimeout(3000);
  await page.goto(`${BASE}/app/notes`, { waitUntil: 'domcontentloaded' });
  await page.waitForTimeout(2500);
  check(
    'signing back in restores the account and its note',
    (await page.locator('body').innerText()).includes('Cloud persistence check'),
  );

  // ── Starter-library import, through the UI, as the owner ────────────────
  // This is the path an owner actually takes on a fresh project: no service
  // account, no CLI, just a button in the admin panel. It is worth testing
  // because the rules only accept those writes for owner/admin, so a mistake
  // in the role check would surface here and nowhere else.
  {
    const app = admin.initializeApp({ projectId: PROJECT });
    const db = app.firestore();
    const users = await app.auth().listUsers();
    const aliceUser = users.users.find((user) => user.email === alice);
    if (!aliceUser) throw new Error('could not find the signed-up account to promote');

    await db.doc(`roles/${aliceUser.uid}`).set({ role: 'owner' });

    // Empty the library so the import panel has something to do.
    for (const name of ['courses', 'resources']) {
      const snapshot = await db.collection(name).get();
      await Promise.all(snapshot.docs.map((doc) => doc.ref.delete()));
    }
    await db.doc('settings/site').delete();

    await page.goto(`${BASE}/admin`, { waitUntil: 'domcontentloaded' });
    await page.waitForTimeout(2500);
    const panel = page.getByRole('button', { name: /import starter library/i });
    const visible = await panel.isVisible().catch(() => false);
    check('the import panel appears when the library is empty', visible);

    if (visible) {
      await panel.click();
      await page.waitForTimeout(4000);
      const text = await page.locator('body').innerText();
      check('import reports success', /Imported \d+ records/i.test(text), text.slice(0, 160));

      const courseCount = (await db.collection('courses').get()).size;
      const resourceCount = (await db.collection('resources').get()).size;
      check('all 7 courses reached Firestore', courseCount === 7, `${courseCount} documents`);
      check('all 6 guides reached Firestore', resourceCount === 6, `${resourceCount} documents`);

      const settingsDoc = await db.doc('settings/site').get();
      check('site settings were written', settingsDoc.exists, String(settingsDoc.exists));

      // And the public library renders from those writes.
      await page.goto(`${BASE}/courses`, { waitUntil: 'domcontentloaded' });
      await page.waitForTimeout(2500);
      check(
        'the imported library is visible on the public site',
        /learning paths|course/i.test(await page.locator('body').innerText()),
      );
    }
  }

  // ── Guest mode: no account, then keep the work ───────────────────────────
  {
    const guestContext = await browser.newContext({ viewport: { width: 1360, height: 900 } });
    const guestPage = await guestContext.newPage();
    await guestPage.goto(`${BASE}/login`, { waitUntil: 'domcontentloaded' });
    await guestPage.waitForTimeout(2000);

    const guestButton = guestPage.getByRole('button', { name: /try it without an account/i }).first();
    check('a guest entry point exists on the login page', await guestButton.isVisible().catch(() => false));

    await guestButton.click();
    await guestPage.waitForURL('**/onboarding', { timeout: 30000 }).catch(() => {});
    check('a guest lands in onboarding', guestPage.url().includes('/onboarding'), guestPage.url());

    await guestPage.waitForSelector('text=Your learning profile', { timeout: 30000 });
    await guestPage.getByRole('button', { name: 'Continue' }).click();
    await guestPage.getByRole('button', { name: 'Grade 10', exact: true }).click();
    await guestPage.getByRole('button', { name: 'Continue' }).click();
    await guestPage.getByRole('button', { name: /Nepal National Curriculum/ }).click();
    await guestPage.getByRole('button', { name: 'Continue' }).click();
    await guestPage.getByRole('button', { name: /^English/ }).first().click();
    await guestPage.getByRole('button', { name: 'Continue' }).click();
    await guestPage.getByRole('button', { name: 'Mathematics', exact: true }).click();
    await guestPage.getByRole('button', { name: 'Continue' }).click();
    await guestPage.getByRole('button', { name: /Prepare for exams/i }).click();
    await guestPage.getByRole('button', { name: 'Continue' }).click();
    await guestPage.getByRole('button', { name: /Step-by-step detailed/i }).click();
    await guestPage.getByRole('button', { name: /Finish setup/i }).click();
    await guestPage.waitForURL('**/app', { timeout: 30000 }).catch(() => {});
    check('a guest reaches the app without an email', guestPage.url().includes('/app'), guestPage.url());

    // A guest can do real work.
    await guestPage.goto(`${BASE}/app/notes`, { waitUntil: 'domcontentloaded' });
    await guestPage.waitForTimeout(2000);
    await guestPage.getByRole('button', { name: /new note/i }).first().click();
    await guestPage.getByLabel('Title', { exact: true }).fill('Guest note to keep');
    await guestPage.getByLabel('Subject', { exact: true }).selectOption({ label: 'Science' });
    await guestPage.getByLabel('Content', { exact: true }).fill('Written while anonymous.');
    await guestPage.getByRole('button', { name: /save note/i }).click();
    await guestPage.waitForTimeout(2500);

    // The banner must warn them, honestly.
    const guestShell = await guestPage.locator('body').innerText();
    check('the guest sees a warning that work is browser-bound', /guest account/i.test(guestShell));

    // Upgrade, and prove the note survives.
    await guestPage.getByRole('button', { name: /keep my progress/i }).first().click();
    await guestPage.waitForTimeout(600);
    const guestEmail = `guest.upgrade.${stamp}@example.test`;
    await guestPage.getByLabel('Your name').last().fill('Former Guest');
    await guestPage.getByLabel('Email address').last().fill(guestEmail);
    await guestPage.getByLabel('Password').last().fill('StudyHard123');
    await guestPage.getByRole('button', { name: /save my account/i }).click();
    await guestPage.waitForTimeout(4000);

    const afterUpgrade = await guestPage.locator('body').innerText();
    const dialogAlert = await guestPage.getByRole('alert').first().innerText().catch(() => '');
    const dialogOpen = await guestPage.getByRole('dialog').count();
    check(
      'the guest banner disappears once the account is saved',
      !/You are using a \*?guest account/i.test(afterUpgrade),
      `dialogOpen=${dialogOpen} alert="${dialogAlert}"`,
    );

    await guestPage.reload({ waitUntil: 'domcontentloaded' });
    await guestPage.waitForTimeout(3000);
    check(
      'the note written as a guest survives the upgrade',
      (await guestPage.locator('body').innerText()).includes('Guest note to keep'),
    );

    await guestContext.close();
  }

  check('no uncaught page errors', pageErrors.length === 0, pageErrors.slice(0, 2).join(' | '));
  await aliceContext.close();
  await bobContext.close();
} catch (error) {
  check('flow completed without throwing', false, error.message.split('\n')[0]);
} finally {
  await browser.close();
  cleanup();
}

const passed = results.filter((r) => r.passed).length;
console.log(`\n${passed}/${results.length} checks passed in ${elapsed()}`);
process.exit(passed === results.length ? 0 : 1);
