// ── 4. Drive the browser ───────────────────────────────────────────────────
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1280, height: 950 } });
const page = await context.newPage();

const consoleErrors = [];
const consoleWarnings = [];
/** Record console noise from any page the run opens, not just the first. */
function watchConsole(target) {
  target.on('console', (msg) => {
    const text = msg.text();
    if (msg.type() === 'error' && !/Failed to load resource/i.test(text)) consoleErrors.push(text);
    if (msg.type() === 'warning') consoleWarnings.push(text);
  });
  target.on('pageerror', (error) => consoleErrors.push(String(error)));
}
watchConsole(page);

try {
  // --- Browsing without an account -----------------------------------------
  await page.goto(`${BASE}/connect`, { waitUntil: 'domcontentloaded' });
  await page.waitForSelector('#main h1', { timeout: 30000 });
  await page.waitForTimeout(1200);
  const hub = await page.locator('body').innerText();
  check('the Connect hub opens with no account', /Study together, not alone/i.test(hub));
  check('the community list is public', /SEE 2026/i.test(hub), hub.slice(0, 120).replace(/\n/g, ' '));

  await page.goto(`${BASE}/connect/c/see-2026`, { waitUntil: 'domcontentloaded' });
  await page.waitForSelector('#main h1', { timeout: 30000 });
  await page.waitForTimeout(1500);
  const guestView = await page.locator('body').innerText();
  check('a community is readable without signing in', /SEE 2026/i.test(guestView));
  check('messages are withheld from a signed-out visitor', /Messages are for members/i.test(guestView));
  check('the reason is explained before asking anything', /private to the people in it/i.test(guestView));

  // --- First sign-in creates a profile --------------------------------------
  await page.getByRole('button', { name: /continue with discord/i }).first().click();
  await page.waitForURL(/\/connect\/c\/see-2026/, { timeout: 45000 });
  await page.waitForTimeout(2500);
  const afterSignIn = await page.locator('body').innerText();
  check('Discord sign-in returns to the page that was requested', /\/connect\/c\/see-2026/.test(page.url()), page.url());
  check('the profile was created from the Discord account', /Riyaz Chalise/i.test(afterSignIn), afterSignIn.slice(0, 140).replace(/\n/g, ' '));

  const profileSnap = await db.doc('connectProfiles/discord_100000000000000001').get();
  check('a Connect profile document exists in Firestore', profileSnap.exists);
  const profile = profileSnap.data() ?? {};
  check('it carries the Discord id and username', profile.discordId === '100000000000000001' && profile.discordUsername === 'riyaz');
  check('it carries an avatar URL from Discord', String(profile.avatarUrl ?? '').includes('cdn.discordapp.com'));
  check('it carries a registration date', typeof profile.createdAt === 'string' && profile.createdAt.length > 10);
  const identity = await db.doc('connectIdentities/100000000000000001').get();
  check('the identity mapping is written server-side', identity.exists && identity.get('uid') === 'discord_100000000000000001');

  const uid = 'discord_100000000000000001';
  const userRecord = await auth.getUser(uid).catch(() => null);
  check('a Firebase user exists for the Discord id', Boolean(userRecord));
  // --- Join, then post -----------------------------------------------------
  await page.getByRole('button', { name: /join see 2026/i }).first().click();
  await page.waitForTimeout(1500);
  const joined = await page.locator('body').innerText();
  check('a signed-in non-member is offered joining', /Join SEE 2026|Message #general/i.test(joined));

  const composer = page.getByRole('textbox', { name: /message #general/i });
  const composerVisible = await composer
    .waitFor({ state: 'visible', timeout: 20000 })
    .then(() => true)
    .catch(() => false);
  check('a member can reach the composer', composerVisible);

  if (composerVisible) {
    const body = `Has anyone got the 2081 science paper? ${Date.now()}`;
    await composer.fill(body);
    await composer.press('Enter');
    await page.waitForTimeout(2500);
    const afterSend = await page.locator('body').innerText();
    check('the message appears in the channel', afterSend.includes(body));

    const messages = await db.collection(`communities/${COMMUNITY_ID}/channels/general/messages`).get();
    check('the message is written to Firestore, not just rendered', messages.docs.some((doc) => doc.get('body') === body));

    await page.reload({ waitUntil: 'domcontentloaded' });
    await page.waitForTimeout(3000);
    const afterReload = await page.locator('body').innerText();
    check('the message survives a reload', afterReload.includes(body));
  }

  // --- A second person cannot read the first person's community -------------
  await fetch(`${DISCORD}/_account?name=aarati`);
  const second = await browser.newContext({ viewport: { width: 1280, height: 950 } });
  const secondPage = await second.newPage();
  await secondPage.goto(`${BASE}/connect/c/see-2026`, { waitUntil: 'domcontentloaded' });
  await secondPage.waitForSelector('#main h1', { timeout: 30000 });
  await secondPage.getByRole('button', { name: /continue with discord/i }).first().click();
  await secondPage.waitForURL(/\/connect/, { timeout: 45000 });
  await secondPage.waitForTimeout(2500);
  const secondUid = 'discord_100000000000000002';
  const secondProfile = await db.doc(`connectProfiles/${secondUid}`).get();
  check('a second Discord account gets its own profile', secondProfile.exists && secondProfile.get('discordUsername') === 'aarati');
  check('the second account is a different Firebase user', secondProfile.get('uid') !== uid);

  const secondView = await secondPage.locator('body').innerText();
  check('a non-member cannot read another community’s messages', /Messages are for members|Join SEE 2026/i.test(secondView));
  const secondMessages = await secondPage
    .getByRole('textbox', { name: /message #general/i })
    .isVisible()
    .catch(() => false);
  check('the composer stays closed to a non-member', secondMessages === false);

  // --- Two members, one conversation, no reload ----------------------------
  // The brief asks for real-time messages. "Appears after a reload" would also
  // pass against a plain fetch, so this keeps both pages open and listens for
  // the write to arrive live in the other person's tab.
  await secondPage.getByRole('button', { name: /join see 2026/i }).first().click();
  const secondComposer = secondPage.getByRole('textbox', { name: /message #general/i });
  const secondCanWrite = await secondComposer
    .waitFor({ state: 'visible', timeout: 20000 })
    .then(() => true)
    .catch(() => false);
  check('a second member can reach the same channel', secondCanWrite);

  if (secondCanWrite && composerVisible) {
    const liveBody = `Live check ${Date.now()}`;
    await composer.fill(liveBody);
    await composer.press('Enter');
    const arrivedLive = await secondPage
      .getByText(liveBody)
      .first()
      .waitFor({ state: 'visible', timeout: 20000 })
      .then(() => true)
      .catch(() => false);
    check('a message reaches another member without a reload', arrivedLive);

    const replyBody = `Got it ${Date.now()}`;
    await secondComposer.fill(replyBody);
    await secondComposer.press('Enter');
    const replyArrivedLive = await page
      .getByText(replyBody)
      .first()
      .waitFor({ state: 'visible', timeout: 20000 })
      .then(() => true)
      .catch(() => false);
    check('replies travel in both directions in real time', replyArrivedLive);
  }

  await second.close();

  // --- Existing user is recognised, not duplicated --------------------------
  const before = (await db.collection('connectProfiles').get()).size;
  const third = await browser.newContext();
  const thirdPage = await third.newPage();
  await fetch(`${DISCORD}/_account?name=riyaz`);
  await thirdPage.goto(`${BASE}/connect/c/see-2026`, { waitUntil: 'domcontentloaded' });
  await thirdPage.waitForSelector('#main h1', { timeout: 30000 });
  await thirdPage.getByRole('button', { name: /continue with discord/i }).first().click();
  await thirdPage.waitForURL(/\/connect/, { timeout: 45000 });
  await thirdPage.waitForTimeout(2000);
  const after = (await db.collection('connectProfiles').get()).size;
  check('signing in again reuses the same profile', after === before, `${before} → ${after}`);
  await third.close();

  // --- Cancelled authorisation ---------------------------------------------
  await fetch(`${DISCORD}/_deny?on=1`);
  const cancelling = await browser.newContext();
  const cancelPage = await cancelling.newPage();
  await cancelPage.goto(`${BASE}/connect/c/see-2026`, { waitUntil: 'domcontentloaded' });
  await cancelPage.waitForSelector('#main h1', { timeout: 30000 });
  await cancelPage.getByRole('button', { name: /continue with discord/i }).first().click();
  await cancelPage.waitForURL(/\/connect\/auth/, { timeout: 45000 });
  // The prerendered shell ships an <h1>, so waiting for it proves nothing —
  // the message only exists once React has mounted. Wait for the text itself.
  await cancelPage
    .getByText(/cancelled the Discord authorisation/i)
    .first()
    .waitFor({ state: 'visible', timeout: 20000 })
    .catch(() => {});
  const cancelText = await cancelPage.locator('body').innerText();
  check('cancelling is reported as a choice, not a crash', /cancelled the Discord authorisation/i.test(cancelText), cancelText.slice(0, 120).replace(/\n/g, ' '));
  // After a refusal the button is relabelled "Try Discord again"; what matters
  // is that a retry is offered and no session was created.
  const retry = await cancelPage.getByRole('button', { name: /continue with discord|try discord again/i }).isVisible();
  check('cancelling leaves the visitor signed out, able to retry', retry);
  const sessionAfterCancel = await cancelPage.evaluate(async () => {
    const response = await fetch('/api/connect/session', { credentials: 'include' });
    return response.status;
  });
  check('no session was minted by a cancelled sign-in', sessionAfterCancel === 401, String(sessionAfterCancel));
  await cancelling.close();
  await fetch(`${DISCORD}/_deny?on=0`);

  // --- Forged state --------------------------------------------------------
  const forged = await fetch(`${BASE}/api/connect/callback?code=whatever&state=forged-state`, {
    redirect: 'manual',
    headers: { cookie: `ujyalo_connect_state=${encodeURIComponent('not-a-real-sealed-cookie')}` },
  });
  const location = forged.headers.get('location') ?? '';
  check('a forged state is rejected before any token exchange', /reason=invalid_state/.test(location), `${forged.status} ${location}`);

  // --- A used handoff cannot be replayed -----------------------------------
  const replay = await fetch(`${BASE}/api/connect/session`);
  check('a missing handoff cookie yields 401, not a token', replay.status === 401, String(replay.status));

  // Membership is written by the server, so the endpoint itself must refuse
  // anyone who is not signed in — otherwise the rules would be decoration.
  const anonymousJoin = await fetch(`${BASE}/api/connect/join`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({ communityId: COMMUNITY_ID }),
  });
  check('joining without a session is refused', anonymousJoin.status === 401, String(anonymousJoin.status));

  const forgedJoin = await fetch(`${BASE}/api/connect/join`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Authorization: 'Bearer not-a-real-token' },
    body: JSON.stringify({ communityId: COMMUNITY_ID }),
  });
  check('joining with a forged token is refused', forgedJoin.status === 401, String(forgedJoin.status));

  // --- Logout --------------------------------------------------------------
  const connected = await browser.newContext({ viewport: { width: 1280, height: 950 } });
  const connectedPage = await connected.newPage();
  watchConsole(connectedPage);
  await fetch(`${DISCORD}/_account?name=riyaz`);
  await connectedPage.goto(`${BASE}/connect/c/see-2026`, { waitUntil: 'domcontentloaded' });
  await connectedPage.waitForSelector('#main h1', { timeout: 30000 });
  await connectedPage.getByRole('button', { name: /continue with discord/i }).first().click();
  await connectedPage.waitForURL(/\/connect/, { timeout: 45000 });
  await connectedPage.waitForTimeout(1500);
  await connectedPage.goto(`${BASE}/connect/me`, { waitUntil: 'domcontentloaded' });
  await connectedPage.waitForSelector('#main h1', { timeout: 30000 });
  await connectedPage
    .getByText(/@riyaz/i)
    .first()
    .waitFor({ state: 'visible', timeout: 20000 })
    .catch(() => {});
  // The community list is a second query; give it its own chance to land.
  await connectedPage
    .getByText(/your communities/i)
    .first()
    .waitFor({ state: 'visible', timeout: 15000 })
    .catch(() => {});
  const profileView = await connectedPage.locator('body').innerText();
  check('the profile page shows the Discord identity', /@riyaz/i.test(profileView), profileView.slice(0, 120).replace(/\n/g, ' '));
  check('it states where the identity came from', /came from Discord/i.test(profileView));
  check('the profile lists the communities joined', /Your communities/i.test(profileView) && /SEE 2026/.test(profileView), profileView.slice(0, 160).replace(/\n/g, ' '));

  // --- The Ujyalo display name is the user's own ---------------------------
  const customName = `Riyaz C. ${Date.now() % 10000}`;
  await connectedPage.getByLabel(/display name/i).first().fill(customName);
  await connectedPage.getByRole('button', { name: /save changes/i }).first().click();
  await connectedPage.getByText(/saved/i).first().waitFor({ state: 'visible', timeout: 15000 }).catch(() => {});
  await connectedPage.waitForTimeout(1200);

  const editedProfile = (await db.doc(`connectProfiles/${uid}`).get()).data() ?? {};
  check('the display name can be changed by the user', editedProfile.displayName === customName, String(editedProfile.displayName));
  check('editing does not overwrite the Discord identity', editedProfile.discordUsername === 'riyaz' && editedProfile.discordId === '100000000000000001');

  await connectedPage.reload({ waitUntil: 'domcontentloaded' });
  await connectedPage.waitForTimeout(2500);
  const afterEdit = await connectedPage.locator('body').innerText();
  check('the new display name survives a reload', afterEdit.includes(customName));

  await connectedPage.getByRole('button', { name: /^sign out$/i }).first().click();
  await connectedPage.waitForTimeout(2500);
  await connectedPage.goto(`${BASE}/connect/me`, { waitUntil: 'domcontentloaded' });
  await connectedPage.waitForTimeout(1500);
  const afterLogout = await connectedPage.locator('body').innerText();
  check('logout ends the session', /needs a Discord account|Continue with Discord/i.test(afterLogout), afterLogout.slice(0, 120).replace(/\n/g, ' '));

  // --- Mobile layout -------------------------------------------------------
  const mobile = await browser.newContext({ ...devices['Pixel 7'] });
  const mobilePage = await mobile.newPage();
  await mobilePage.goto(`${BASE}/connect`, { waitUntil: 'domcontentloaded' });
  await mobilePage.waitForSelector('#main h1', { timeout: 30000 });
  const overflow = await mobilePage.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
  check('the Connect hub does not overflow a phone screen', !overflow);
  await mobilePage.goto(`${BASE}/connect/auth`, { waitUntil: 'domcontentloaded' });
  await mobilePage.waitForTimeout(800);
  const mobileAuthOverflow = await mobilePage.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
  check('the Discord sign-in page fits a phone screen', !mobileAuthOverflow);
  await mobile.close();

  check('no console errors during the whole run', consoleErrors.length === 0, consoleErrors.slice(0, 2).join(' | '));
  check('nothing warned about a failed community listing', !consoleWarnings.some((w) => /could not list communities/.test(w)), consoleWarnings.slice(0, 2).join(' | '));
} catch (error) {
  check('flow completed without throwing', false, String(error).slice(0, 300));
} finally {
  await browser.close();
  await deleteApp(app);
}

const passed = results.filter((r) => r.passed).length;
console.log(`\n${passed}/${results.length} checks passed in the Connect suite.`);
process.exit(passed === results.length ? 0 : 1);
