/**
 * Ujyalo Connect — end-to-end Discord sign-in and community run.
 *
 * Drives the real app in Chromium against the Auth and Firestore emulators and
 * a local Discord stand-in. No Discord application, client secret or Firebase
 * project is needed, and nothing is mocked inside the app itself: the OAuth
 * endpoints, the transaction, the rules and the UI are all the production code.
 *
 * What it proves, in the brief's words:
 *   - a new Discord account gets a profile on first sign-in;
 *   - an existing account is recognised instead of duplicated;
 *   - cancelling authorisation, a forged state and an expired session all fail
 *     cleanly rather than half-signing someone in;
 *   - browsing communities needs no account, posting does;
 *   - a second person cannot read the first person's community;
 *   - logout really ends the session.
 *
 * Run:  npm run test:connect
 */
