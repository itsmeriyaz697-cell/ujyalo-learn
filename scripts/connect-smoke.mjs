const children = [];
function spawnChild(name, command, args, env = {}) {
  const child = spawn(command, args, {
    cwd: ROOT,
    stdio: ['ignore', 'pipe', 'pipe'],
    detached: true,
    env: { ...process.env, ...env },
  });
  let log = '';
  child.stdout.on('data', (chunk) => (log += chunk));
  child.stderr.on('data', (chunk) => (log += chunk));
  children.push({ name, child, log: () => log });
  return child;
}

function cleanup() {
  for (const entry of children) {
    try {
      process.kill(-entry.child.pid, 'SIGKILL');
    } catch {
      /* already gone */
    }
  }
  try {
    fs.unlinkSync(path.join(ROOT, '.env.connect'));
  } catch {
    /* nothing to remove */
  }
}
process.on('exit', cleanup);
process.on('SIGINT', () => process.exit(130));

async function waitForPort(port, timeoutMs = 60000) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    const open = await new Promise((resolve) => {
      const socket = net.connect(port, '127.0.0.1');
      socket.on('connect', () => (socket.end(), resolve(true)));
      socket.on('error', () => resolve(false));
      socket.setTimeout(1000, () => (socket.destroy(), resolve(false)));
    });
    if (open) return true;
    await new Promise((resolve) => setTimeout(resolve, 300));
  }
  return false;
}

function fail(message) {
  console.error(`\n✗ ${message}`);
  for (const entry of children) {
    const tail = entry.log().split('\n').slice(-8).join('\n');
    if (tail.trim()) console.error(`\n--- ${entry.name} ---\n${tail}`);
  }
  process.exit(1);
}

// ── 2. Start the mock Discord, the dev API and the app ─────────────────────
