spawnChild('api', 'npx', ['tsx', 'server/dev-api.ts'], connectEnv);
// The app's /api requests are proxied, so the proxy must be told where this
// suite's API actually is. Without this the browser talked to port 8787, got
// nothing back, and the OAuth redirect silently never happened.
spawnChild('web', 'npx', ['vite', '--mode', 'connect', '--port', String(WEB_PORT), '--strictPort', '--host', '127.0.0.1'], {
  API_PROXY_TARGET: `http://127.0.0.1:${API_PORT}`,
});

const up = await Promise.all([
  waitForPort(DISCORD_PORT),
  waitForPort(API_PORT),
  waitForPort(WEB_PORT),
]);
