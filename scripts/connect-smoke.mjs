  AI_API_KEY: 'unused-in-this-suite',
  DISCORD_CLIENT_ID: 'test-client-id',
  DISCORD_CLIENT_SECRET: 'test-client-secret',
  DISCORD_REDIRECT_URI: `${BASE}/api/connect/callback`,
  CONNECT_SESSION_SECRET: SESSION_SECRET,
